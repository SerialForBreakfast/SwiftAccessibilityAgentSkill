"""Pool coverage: tasks by cell × workstream, evidence status, split, and inventory links.

  python3 -B evals/pool/coverage.py           print the report
  python3 -B evals/pool/coverage.py --write   also write COVERAGE.md
Reads task.json files and recorded scorecards only; runs nothing.
"""
import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
INV = json.loads((ROOT / "research/evaluation/failure-inventory/inventory.json").read_bytes())
CELLS = ["ios-uikit", "ios-swiftui", "macos-appkit", "macos-swiftui", "tvos-uikit", "tvos-swiftui"]
WS = [f"W{i}" for i in range(1, 10)]


def tasks():
    for f in sorted(HERE.glob("*/*/task.json")):
        m = json.loads(f.read_bytes())
        card = HERE / m["cell"] / "scorecard.json"
        m["recorded"] = card.exists() and any(r["task"] == m["id"] for r in json.loads(card.read_bytes())["rows"])
        yield m


def report():
    ts = list(tasks())
    inv = {r["case"]: r for r in INV["cases"]}
    grid = defaultdict(Counter)
    for t in ts:
        grid[t["cell"]][t["workstream"]] += 1
    L = ["# Pool coverage", "", "Generated by `python3 -B evals/pool/coverage.py --write`.", "",
         f"**{len(ts)} tasks** · " + " · ".join(f"{k} {v}" for k, v in sorted(Counter(t['evidence']['status'] for t in ts).items()))
         + " · " + " · ".join(f"{k} {v}" for k, v in sorted(Counter(t['split'] for t in ts).items()))
         + f" · recorded {sum(t['recorded'] for t in ts)}", "",
         "| Cell | " + " | ".join(WS) + " | Total |", "|---|" + "---:|" * (len(WS) + 1)]
    for c in CELLS:
        L.append(f"| {c} | " + " | ".join(str(grid[c][w] or "") for w in WS) + f" | {sum(grid[c].values())} |")
    L += ["", "## Tasks", "", "| Cell | Task | WS | Split | Evidence | Inventory link | Recorded |", "|---|---|---|---|---|---|---|"]
    for t in ts:
        e = t["evidence"]
        link = e.get("inventoryCase", "")
        disp = inv[link]["disposition"].split(":")[0] if link in inv else ("" if not link else "unknown case")
        L.append(f"| {t['cell']} | `{t['id']}` | {t['workstream']} | {t['split']} | {e['status']} | "
                 f"{link + (' (' + disp + ')' if disp else '')} | {'yes' if t['recorded'] else ''} |")
    target = [r["case"] for r in INV["cases"] if r["disposition"].startswith("fix")]
    covered = {t["evidence"].get("inventoryCase") for t in ts}
    L += ["", "**Inventory cases failing on the target model with no pool task yet:** "
          + (", ".join(f"`{c}`" for c in target if c not in covered) or "none"), ""]
    return "\n".join(L)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true")
    text = report()
    if p.parse_args().write:
        (HERE / "COVERAGE.md").write_text(text)
    print(text)
