"""Verify the rc.1 return end to end and link every displayed number to its evidence.

Chain per cell: original answer -> strict extraction -> submission hash -> task and oracle hash ->
first native scorecard -> summary.json row -> RESULT.md decision table.

  python3 -B evals/rc1-comparison/verify_return.py            check (private evidence if present)
  python3 -B evals/rc1-comparison/verify_return.py --write    regenerate summary.json and the table

Without the private bundles (a clean checkout), it checks only what is public: summary.json's internal
consistency, oracle hashes recomputed from tasks.py, and the RESULT.md table rendered from summary.json.
It says which checks were skipped. It never extracts or executes bundle content.
"""
import argparse
from collections import Counter
from hashlib import sha256
import json
import os
from pathlib import Path
import sys
from zipfile import ZipFile

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "evals/rc1/grader"))
sys.path.insert(0, str(ROOT / "evals/protocol"))
from tasks import TASKS
from grade import oracle
from answer_contract import extract

RUN = ROOT / "evals/results/rc1-return-20261107"
BUNDLES = RUN / "bundles"
CELLS = RUN / "native/cells"
SUMMARY = HERE / "summary.json"
RESULT = HERE / "RESULT.md"
PACKET = HERE / "packet.json"
SUMS = {
    "rc1-release-native-36-v1-return.zip": "77f942cd11071cef336e49ff0977777dd6f3f9bbf499014a171812769c3a80fa",
    "rc1-release-native-chat-36-v2-return.zip": "9f7d0cea62392c12d343efe9b698bb205a444374087fa01d9da40a7511ce4cad",
    "rc1-failure-replay-handoff-return.zip": "4f08fcc6f717140e1e76602f7ac743e6daa52333765a24927fbcf5c7577cbae8",
}
SEALED_PACKET = "496c51e084498d3eb164cc5a74b0c6398ec654d9acc686212b526f6e492f69c2"
V2_PACKET = "46d576c8e89cfe37236c74d387350b04a61130f2ac7fbf0c4839b32f0aae05ca"
ARMS = ("0.2.2", "0.3.0-rc.1")
ORACLES = {t.id: sha256(oracle(t).encode()).hexdigest() for t in TASKS}
BEGIN, END = "<!-- summary:begin (generated by verify_return.py --write) -->", "<!-- summary:end -->"
digest = lambda b: sha256(b).hexdigest()


def bundle(name):
    assert digest((BUNDLES / name).read_bytes()) == SUMS[name], name + " hash"
    z = ZipFile(BUNDLES / name)
    sums = json.loads(z.read("checksums.json"))
    items = sums.items() if isinstance(sums, dict) else [(e["path"], e["sha256"]) for e in sums]
    for path, h in items:
        assert digest(z.read(path)) == h, name + ": " + path
    return z


def reference_reads(activation):
    ok = {r["tool_id"] for r in activation["results"] if not r["is_error"]}
    return sum(c["name"] == "Read" and "/references/" in c["arguments"].get("file_path", "") and c["tool_id"] in ok
               for c in activation["calls"])


def build():
    """Recompute summary.json from private evidence."""
    sealed = json.loads(PACKET.read_bytes())
    assert digest(PACKET.read_bytes()) == SEALED_PACKET
    prompts = {c["cell"]: c["promptSHA256"] for c in sealed["cells"]}
    v1, v2, replay = (bundle(n) for n in SUMS)
    for z in (v1, v2):
        assert digest(z.read("evals/rc1-comparison/packet.json")) == SEALED_PACKET
    assert digest(v2.read("controller/packet.json")) == V2_PACKET
    assert {"README.md", "NEXT.md"} <= set(replay.namelist())
    i1, i2 = (json.loads(z.read("index.json")) for z in (v1, v2))
    by1 = {r["cell"]: r for r in i1}
    sealed_rows = [dict(cell=r["cell"], task=r["task"], arm=r["arm"], lane=r["lane"], state=r["state"],
                        promptMatchesSeal=r["promptSHA256"] == prompts[r["cell"]],
                        source=r.get("source_grade"), invoked=bool(r.get("invoked"))) for r in i1]
    rows = []
    for r in i2:
        answer = v2.read(f"cells/{r['cell']}/answer.txt")
        x = extract(answer.decode("utf-8"))
        g = json.loads(v2.read(f"cells/{r['cell']}/grade.json"))
        act = json.loads(v2.read(f"cells/{r['cell']}/activation.json"))
        rec = json.loads((CELLS / f"{r['cell']}.json").read_bytes())
        card_path = ROOT / rec["scorecard"]
        card = json.loads(card_path.read_bytes())
        graded = card["rows"][0]
        sub = digest(x["code"])
        # The links: answer bytes -> extraction -> graded bytes -> task oracle -> scorecard -> record.
        assert x["status"] == "accepted", r["cell"]
        assert rec["answerSHA256"] == digest(answer) and rec["submissionSHA256"] == sub
        assert graded["submissionSHA256"] == sub and graded["task"] == r["task"], r["cell"]
        assert graded["oracleSHA256"] == ORACLES[r["task"]], r["cell"] + " oracle"
        assert rec["scorecardSHA256"] == digest(card_path.read_bytes()) and rec["status"] == graded["status"]
        assert r["session_id"] != by1[r["cell"]].get("session_id")
        rows.append(dict(cell=r["cell"], task=r["task"], arm=r["arm"], lane=r["lane"],
                         promptMatchesSeal=r["promptSHA256"] == prompts[r["cell"]],
                         answerSHA256=digest(answer), extraction=x["status"], format=x["format"],
                         submissionSHA256=sub, oracleSHA256=graded["oracleSHA256"],
                         source=g["verdict"], native=graded["status"], scorecardSHA256=rec["scorecardSHA256"],
                         laterGradings=[l["status"] for l in rec["laterGradings"]],
                         invoked=bool(r.get("invoked")), referenceReads=reference_reads(act),
                         announced=bool(r.get("announced")), routingReported=bool(r.get("routing_reported"))))
    return dict(job="rc.1 vs 0.2.2 return intake", sealedPacketSHA256=SEALED_PACKET, derivedPacketSHA256=V2_PACKET,
                bundles=SUMS, gradedBy="evals/rc1/grader/grade.py at 226b3a4 (reviewed local lane)",
                evidence="rows need the private bundles to re-derive; counts below are checkable from rows",
                sealed=sealed_rows, diagnostic=rows)


def pairs(rows, key):
    by = {}
    for r in rows:
        if r["lane"] == "automatic":
            by.setdefault(r["task"], {})[r["arm"]] = r
    out = Counter()
    for task, b in by.items():
        if len(b) < 2 or any(b[a].get(key) is None for a in ARMS):
            out["incomplete"] += 1
            continue
        good = lambda v: v in ("meets", "pass")
        x, y = (good(b[a][key]) for a in ARMS)
        out["both-pass" if x and y else "both-fail" if not (x or y) else "gain" if y else "loss"] += 1
    return dict(sorted(out.items()))


def counts(s):
    """Every number the decision table displays, derived only from summary rows."""
    sealed, rows = s["sealed"], s["diagnostic"]
    lane = lambda l, a: [r for r in rows if r["lane"] == l and r["arm"] == a]
    font = [r for r in rows if r["task"] == "checkout-font" and r["native"] != "pass"]
    first = {(r["task"], r["arm"]): r for r in rows if r["lane"] == "automatic"}
    reps = [r for r in rows if r["lane"] == "repeat-automatic"]
    return {
        "sealedAttempted": sum(r["state"] in ("completed", "attempt-error") for r in sealed),
        "sealedCompleted": sum(r["state"] == "completed" for r in sealed),
        "sealedPromptsMatch": sum(r["promptMatchesSeal"] for r in sealed),
        "sealedPairs": pairs([dict(r, source=r["source"] if r["state"] == "completed" else None) for r in sealed], "source"),
        "sealedInvoked": sum(r["invoked"] for r in sealed if r["state"] == "completed"),
        "diagnosticCompleted": len(rows),
        "diagnosticPromptsMatch": sum(r["promptMatchesSeal"] for r in rows),
        "totalAttemptedAcrossJobs": sum(r["state"] in ("completed", "attempt-error") for r in sealed) + len(rows),
        "sourcePairs": pairs(rows, "source"),
        "nativePairs": pairs(rows, "native"),
        "nativeTotals": dict(sorted(Counter(r["native"] for r in rows).items())),
        "distinctSubmissions": len({r["submissionSHA256"] for r in rows}),
        "failingImplementations": len({r["submissionSHA256"] for r in font}),
        "sourceNativeDisagreements": sorted(r["cell"] for r in rows if (r["source"] == "meets") != (r["native"] == "pass")),
        "repeatAgreementNative": sum(r["native"] == first[r["task"], r["arm"]]["native"] for r in reps),
        "repeats": len(reps),
        "formats": dict(sorted(Counter(r["format"] for r in rows).items())),
        "invoked": {f"{l} {a}": f"{sum(r['invoked'] for r in lane(l, a))}/{len(lane(l, a))}"
                    for l in ("automatic", "repeat-automatic", "explicit") for a in ARMS if lane(l, a)},
        "referenceReadSessions": {f"{l} {a}": f"{sum(r['referenceReads'] > 0 for r in lane(l, a))}/{len(lane(l, a))}"
                                  for l in ("automatic", "repeat-automatic", "explicit") for a in ARMS if lane(l, a)},
    }


def table(c):
    p = lambda d: ", ".join(f"{k} {v}" for k, v in d.items())
    rows = [
        ("Sealed run: attempted / completed", f"{c['sealedAttempted']}/36 attempted, {c['sealedCompleted']} completed; prompts match seal {c['sealedPromptsMatch']}/36"),
        ("Sealed automatic pairs (source)", p(c["sealedPairs"])),
        ("Sealed automatic invocation", f"{c['sealedInvoked']}/{c['sealedCompleted']}"),
        ("Diagnostic rerun: completed", f"{c['diagnosticCompleted']}/36; prompts match seal {c['diagnosticPromptsMatch']}/36"),
        ("Sessions attempted across both jobs", f"{c['totalAttemptedAcrossJobs']} against a 36-session authorization"),
        ("Diagnostic automatic pairs, source review", p(c["sourcePairs"])),
        ("Diagnostic automatic pairs, native units", p(c["nativePairs"])),
        ("Native outcomes, all 36 cells", p(c["nativeTotals"]) + f"; {c['distinctSubmissions']} distinct submissions"),
        ("checkout-font failures", f"{c['failingImplementations']} distinct implementations; source/native disagree on {', '.join(c['sourceNativeDisagreements'])}"),
        ("0.2.2 repeats agreeing (native)", f"{c['repeatAgreementNative']}/{c['repeats']}"),
        ("Answer format (single fenced block)", p(c["formats"])),
    ] + [(f"Invoked: {k}", v) for k, v in c["invoked"].items()] + [
        (f"Reference read: {k}", v) for k, v in c["referenceReadSessions"].items()]
    return "\n".join(["| Measure | Value |", "|---|---|"] + [f"| {a} | {b} |" for a, b in rows])


def render(text, c):
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    return head + BEGIN + "\n" + table(c) + "\n" + END + tail


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    private = all((BUNDLES / n).exists() for n in SUMS) and CELLS.exists() and not os.getenv("RC1_PUBLIC_ONLY")
    if args.write:
        assert private, "regenerating needs the private evidence"
        s = build()
        s["counts"] = counts(s)
        SUMMARY.write_text(json.dumps(s, indent=2) + "\n")
        RESULT.write_text(render(RESULT.read_text(), s["counts"]))
    s = json.loads(SUMMARY.read_bytes())
    if private:
        fresh = build()
        assert {k: fresh[k] for k in fresh} == {k: s[k] for k in fresh}, "summary.json differs from private evidence"
    for r in s["diagnostic"]:
        assert r["oracleSHA256"] == ORACLES[r["task"]], r["cell"]
    assert s["counts"] == counts(s), "summary counts differ from summary rows"
    assert RESULT.read_text() == render(RESULT.read_text(), s["counts"]), "RESULT.md table differs from summary.json"
    c = s["counts"]
    scope = "private evidence re-derived" if private else "PUBLIC ONLY: rows not re-derived (private bundles absent)"
    print(f"PASS ({scope}): sealed {c['sealedCompleted']}/36 completed; diagnostic native {c['nativeTotals']}, "
          f"pairs {c['nativePairs']}; {c['distinctSubmissions']} distinct; "
          f"{c['failingImplementations']} failing implementations; RESULT.md table matches.")


if __name__ == "__main__":
    main()
